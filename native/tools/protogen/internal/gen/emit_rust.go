package gen

import (
	"fmt"
	"sort"
	"strings"
)

// GeneratedHeader is stamped on every emitted file.
const GeneratedHeader = "// @generated by native/tools/protogen — DO NOT EDIT"

// tsGeneratedHeader is the same marker in TypeScript comment syntax.
const tsGeneratedHeader = GeneratedHeader

// nullHelperModule is the emitted Rust module holding the deserialisation
// helper that turns a JSON null into a default value. Go marshals a nil slice
// or map as null rather than omitting it, and serde's Vec/HashMap cannot
// deserialise null, so every non-optional container field routes through it.
const nullHelperModule = "null_default"

// rustPrims maps IR primitives to Rust types.
var rustPrims = map[string]string{
	primString: "String",
	primBool:   "bool",
	primI8:     "i8",
	primI16:    "i16",
	primI32:    "i32",
	primI64:    "i64",
	primU8:     "u8",
	primU16:    "u16",
	primU32:    "u32",
	primU64:    "u64",
	primF32:    "f32",
	primF64:    "f64",
	primJSON:   "serde_json::Value",
	// time.Time is marshalled by encoding/json as an RFC 3339 string. It is
	// emitted as String rather than a chrono/time type so crowbar-proto stays
	// dependency-free and lossless: the daemon's exact rendering (including
	// its nanosecond precision and offset) round-trips byte for byte.
	primTime: "String",
	// A Go []byte is base64-encoded by encoding/json into a JSON string.
	primBytes: "String",
}

// EmitRust renders every module as a Rust file plus a mod.rs, keyed by file
// name. The returned map is complete: writing exactly these files reproduces
// the crate module.
func EmitRust(
	r *Result,
) map[string]string {
	files := map[string]string{}
	modules := r.Modules()
	aliases := nullableAliases(r)
	for _, m := range modules {
		files[m+".rs"] = rustModule(m, r.DeclsFor(m), aliases)
	}
	files[nullHelperModule+".rs"] = rustNullHelper()

	var b strings.Builder
	b.WriteString(GeneratedHeader + "\n")
	b.WriteString("//\n")
	b.WriteString("// Wire DTOs for the Crowbar daemon's v0 HTTP surface, generated from the Go\n")
	b.WriteString("// handlers. One module per Go package.\n")
	b.WriteString("//\n")
	b.WriteString("// Encoding notes, all of which mirror what encoding/json actually does:\n")
	b.WriteString("//   * time.Time is a String (RFC 3339, as time.Time's MarshalJSON writes it).\n")
	b.WriteString("//   * int64/uint64 are i64/u64 numbers; the daemon uses no `,string` tags.\n")
	b.WriteString("//   * []byte is a String (encoding/json base64-encodes it).\n")
	b.WriteString("//   * A nil Go slice or map marshals as null, so non-optional container\n")
	b.WriteString("//     fields deserialise null as an empty collection.\n")
	b.WriteString("//   * Named Go string types carry an `Other(String)` fallback, because a Go\n")
	b.WriteString("//     string constant set is open: the zero value \"\" is a legal value the\n")
	b.WriteString("//     constants never name.\n")
	b.WriteString("\n")
	names := append([]string{}, modules...)
	names = append(names, nullHelperModule)
	sort.Strings(names)
	for _, m := range names {
		b.WriteString("pub mod " + m + ";\n")
	}
	files["mod.rs"] = b.String()
	return files
}

// rustNullHelper renders the null-coercing deserialiser module.
func rustNullHelper() string {
	return GeneratedHeader + `
//
// Go marshals a nil slice or map as JSON null rather than omitting it, and
// serde refuses null for Vec/HashMap. Every non-optional container field
// deserialises through this helper so a nil-on-the-wire collection arrives as
// an empty one instead of failing the whole response.

use serde::Deserialize;

/// Deserialise T, mapping a JSON null onto T::default().
pub fn null_to_default<'de, D, T>(
    deserializer: D,
) -> Result<T, D::Error>
where
    D: serde::Deserializer<'de>,
    T: Default + Deserialize<'de>,
{
    Ok(Option::<T>::deserialize(deserializer)?.unwrap_or_default())
}
`
}

// nullableAliases returns the set of emitted aliases whose underlying type can
// arrive as a JSON null: a named Go slice or map is still nil-able, and a field
// typed by that alias needs the same null coercion a bare slice field gets.
func nullableAliases(
	r *Result,
) map[string]bool {
	out := map[string]bool{}
	for _, d := range r.Decls {
		if d.Kind != KindAlias || d.Underlying == nil {
			continue
		}
		switch d.Underlying.Container {
		case "slice", "map", "option":
			out[d.Module+"."+d.Name] = true
		}
	}
	return out
}

// refNullable reports whether a resolved reference can carry a JSON null.
func refNullable(
	ref TypeRef,
	aliases map[string]bool,
) bool {
	switch ref.Container {
	case "slice", "map", "option":
		return true
	}
	if ref.Name != "" {
		return aliases[ref.Module+"."+ref.Name]
	}
	return false
}

// rustModule renders one module file.
func rustModule(
	module string,
	decls []Decl,
	aliases map[string]bool,
) string {
	var b strings.Builder
	b.WriteString(GeneratedHeader + "\n")
	b.WriteString("#![allow(non_snake_case, clippy::all)]\n")
	b.WriteString("\n")
	for i, d := range decls {
		if i > 0 {
			b.WriteString("\n")
		}
		switch d.Kind {
		case KindStruct:
			b.WriteString(rustStruct(d, aliases))
		case KindEnum:
			b.WriteString(rustEnum(d))
		case KindAlias:
			b.WriteString(rustAlias(d))
		}
	}
	return b.String()
}

// rustDoc renders a doc comment block at the given indent.
func rustDoc(
	doc string,
	indent string,
) string {
	var b strings.Builder
	for _, line := range docLines(doc) {
		b.WriteString(indent + "///")
		if line != "" {
			b.WriteString(" " + line)
		}
		b.WriteString("\n")
	}
	return b.String()
}

// rustStruct renders a struct declaration.
func rustStruct(
	d Decl,
	aliases map[string]bool,
) string {
	var b strings.Builder
	b.WriteString(rustDoc(d.Doc, ""))
	b.WriteString(rustDroppedNote(d))
	b.WriteString("#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n")
	camel := allFieldsCamel(d.Fields)
	if camel {
		b.WriteString("#[serde(rename_all = \"camelCase\")]\n")
	}
	generics := ""
	if d.Generic {
		generics = "<T>"
	}
	b.WriteString("pub struct " + d.Name + generics + " {\n")
	for _, f := range d.Fields {
		b.WriteString(rustField(f, camel, aliases))
	}
	b.WriteString("}\n")
	return b.String()
}

// rustDroppedNote writes an INCOMPLETE banner onto a struct that lost a field.
// The type still compiles and still deserialises, so without the banner the one
// thing a reader must know — that a key on the wire has no home here — would be
// invisible at the point of use.
func rustDroppedNote(
	d Decl,
) string {
	if len(d.Dropped) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("/// INCOMPLETE: protogen could not lower every field of this type.\n")
	for _, u := range d.Dropped {
		b.WriteString("/// - " + u.What + ": " + u.Reason + "\n")
	}
	return b.String()
}

// allFieldsCamel reports whether a single rename_all = "camelCase" attribute
// reproduces every field's JSON name, which keeps the emitted struct readable
// instead of stamping a rename on every line.
func allFieldsCamel(
	fields []Field,
) bool {
	if len(fields) == 0 {
		return false
	}
	for _, f := range fields {
		rust := toSnake(f.JSONName)
		if escapeRustIdent(rust) != rust {
			return false
		}
		if toCamel(rust) != f.JSONName {
			return false
		}
	}
	return true
}

// rustField renders one struct field with its serde attributes.
func rustField(
	f Field,
	camel bool,
	aliases map[string]bool,
) string {
	var b strings.Builder
	b.WriteString(rustDoc(f.Doc, "    "))
	name := escapeRustIdent(toSnake(f.JSONName))
	attrs := []string{}
	// With rename_all = "camelCase" the container attribute already produces
	// every JSON name (allFieldsCamel proved the round trip), so a per-field
	// rename is only needed when that attribute is absent.
	if !camel && name != f.JSONName {
		attrs = append(attrs, fmt.Sprintf("rename = %q", f.JSONName))
	}
	ty := rustType(f.Type)
	switch {
	case f.Optional:
		// A pointer field already lowered to an option container; wrapping it
		// again would produce Option<Option<T>>, which no JSON ever matches.
		if f.Type.Container != "option" {
			ty = "Option<" + ty + ">"
		}
		attrs = append(attrs, "default", "skip_serializing_if = \"Option::is_none\"")
	case refNullable(f.Type, aliases):
		attrs = append(attrs, "default",
			fmt.Sprintf("deserialize_with = %q", "super::"+nullHelperModule+"::null_to_default"))
	case f.Type.Prim == primJSON:
		attrs = append(attrs, "default")
	}
	if len(attrs) > 0 {
		b.WriteString("    #[serde(" + strings.Join(attrs, ", ") + ")]\n")
	}
	b.WriteString("    pub " + name + ": " + ty + ",\n")
	return b.String()
}

// rustType renders a type reference.
func rustType(
	ref TypeRef,
) string {
	switch ref.Container {
	case "option":
		return "Option<" + rustType(*ref.Elem) + ">"
	case "slice":
		return "Vec<" + rustType(*ref.Elem) + ">"
	case "map":
		return "std::collections::HashMap<" + rustType(*ref.Key) + ", " + rustType(*ref.Elem) + ">"
	}
	if ref.Name != "" {
		return "super::" + ref.Module + "::" + ref.Name
	}
	if ref.Prim == "T" {
		return "T"
	}
	if p, ok := rustPrims[ref.Prim]; ok {
		return p
	}
	return "serde_json::Value"
}

// rustEnum renders a Go string-constant set as a Rust enum. The trailing
// untagged Other(String) variant is load-bearing: a Go named string type is an
// open set whose zero value is "", which no constant declares, so a closed
// enum would fail to deserialise perfectly valid daemon output.
func rustEnum(
	d Decl,
) string {
	var b strings.Builder
	b.WriteString(rustDoc(d.Doc, ""))
	b.WriteString("#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n")
	b.WriteString("pub enum " + d.Name + " {\n")
	used := map[string]bool{}
	for _, v := range d.Variants {
		b.WriteString(rustDoc(v.Doc, "    "))
		name := variantName(d, v, used)
		b.WriteString(fmt.Sprintf("    #[serde(rename = %q)]\n", v.Value))
		b.WriteString("    " + name + ",\n")
	}
	b.WriteString("    /// Any other value the daemon sends, including the zero value \"\".\n")
	b.WriteString("    #[serde(untagged)]\n")
	b.WriteString("    Other(String),\n")
	b.WriteString("}\n")
	return b.String()
}

// variantName derives a unique Rust variant identifier from a wire value,
// falling back to the Go constant name when the value yields nothing usable.
func variantName(
	d Decl,
	v EnumVariant,
	used map[string]bool,
) string {
	name := toUpperCamel(v.Value)
	if name == "" {
		name = strings.TrimPrefix(v.GoName, d.Name)
	}
	if name == "" {
		name = v.GoName
	}
	name = escapeRustIdent(name)
	if name == "Other" {
		name = "Other_"
	}
	candidate := name
	for i := 2; used[candidate]; i++ {
		candidate = fmt.Sprintf("%s%d", name, i)
	}
	used[candidate] = true
	return candidate
}

// rustAlias renders a named Go type whose underlying type is not a struct.
func rustAlias(
	d Decl,
) string {
	var b strings.Builder
	b.WriteString(rustDoc(d.Doc, ""))
	b.WriteString("pub type " + d.Name + " = " + rustType(*d.Underlying) + ";\n")
	return b.String()
}
