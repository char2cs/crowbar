#!/usr/bin/env bash
# Writes docs/plans/2026-11-14-standards-burndown.md: findings per crate/package and rule from the three checkers.
# Usage: standards-burndown.sh [OUTPUT]
set -uo pipefail
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
out=${1:-$repo/docs/plans/2026-11-14-standards-burndown.md}

collect_rust() {
  local root=$1 label=$2
  bash "$here/check-rust-rules.sh" "$root" --strict 2>&1 | grep -v '\[baseline' | grep -E '^[^ ]+:[0-9]+: \[' | sed -E "s#^${root#"$repo"/}/##" | awk -v label="$label" '
    { split($1, p, "/"); unit = (p[1] == "crates" || p[1] == "tests") ? p[2] : (p[1] == "src" ? label : p[1])
      match($0, /\[[a-z-]+\]/); tag = substr($0, RSTART + 1, RLENGTH - 2); print "rust\t" unit "\t" tag }'
}
collect_ts() {
  bash "$here/check-ts-rules.sh" --strict 2>&1 | grep -v '\[baseline' | grep -E '^[^ ]+:[0-9]+: \[' | sed -E 's#^app/panes/##' | awk '{ split($1, p, "/"); unit = (p[3] == "" ? p[1] : p[1] "/" p[2]); match($0, /\[[a-z-]+\]/); print "ts\t" unit "\t" substr($0, RSTART + 1, RLENGTH - 2) }'
}

{
  echo "# Standards burndown"
  echo
  echo "Generated by \`tools/scripts/standards-burndown.sh\` on $(date -u +%F\ %H:%M)Z. Counts of findings per unit and rule from \`check-standards.sh\`; every cell must reach zero before merge. Re-run after each fix cycle."
  echo
} >"$out"
{
  collect_rust "$repo/app/crates" ""
  collect_rust "$repo/app/desktop" "desktop/app"
  collect_rust "$repo/app/mobile/ios-plugin" "ios-plugin"
  bash "$here/check-swift-rules.sh" --strict 2>&1 | grep -v '\[baseline' | grep -E '^[^ ]+:[0-9]+: \[' | awk '{ match($0, /\[[a-z-]+\]/); print "swift\tios\t" substr($0, RSTART + 1, RLENGTH - 2) }'
  collect_ts
} | awk -F'\t' '
  { n[$1 "\t" $2 "\t" $3]++; unit[$1 "\t" $2] += 1; tags[$3] += 1; total[$1 "\t" $2]++ }
  END {
    for (u in total) { split(u, a, "\t"); lang[a[1]] = lang[a[1]] "\n" a[2] }
    for (l in lang) {
      print "## " l "\n"
      nt = 0; delete cols
      for (k in n) { split(k, a, "\t"); if (a[1] == l && !(a[3] in cols)) { cols[a[3]] = tags[a[3]]; nt++ } }
      hdr = "| unit | total |"; sep = "|---|---|"
      order = ""
      for (t in cols) order = order " " t
      split(order, ord, " ")
      for (i = 1; i in ord; i++) for (j = i + 1; j in ord; j++) if (cols[ord[j]] > cols[ord[i]]) { x = ord[i]; ord[i] = ord[j]; ord[j] = x }
      for (i = 1; i in ord; i++) { hdr = hdr " " ord[i] " |"; sep = sep "---|" }
      print hdr; print sep
      split(lang[l], us, "\n")
      for (i in us) if (us[i] != "") {
        row = "| " us[i] " | " total[l "\t" us[i]] " |"
        for (c = 1; c in ord; c++) row = row " " (n[l "\t" us[i] "\t" ord[c]] + 0) " |"
        print row
      }
      print ""
    }
  }' >>"$out"
echo "wrote $out"
